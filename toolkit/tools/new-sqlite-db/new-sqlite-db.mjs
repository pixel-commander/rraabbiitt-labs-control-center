import path from "node:path";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { filename, directory } from "../new-sqlite-db/database-tools.mjs";

async function create(input = {}) {
  const parent = directory(input.path);
  const name = input.name ?? "db";
  if (
    typeof name !== "string" ||
    !/^[a-z][a-z0-9-]*$/.test(name) ||
    /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i.test(name)
  )
    throw Error("name must be a lowercase folder name");
  const file = filename(input.file);
  const folder = path.join(parent, name);
  // Non-recursive creation refuses existing destinations and missing parents.
  await mkdir(folder);
  try {
    await mkdir(path.join(folder, "tables"));
    const artifacts = {
      [file]: "",
      "tables/.gitkeep": "",
      ".gitignore": "*-wal\n*-shm\n*-journal\n",
      "README.txt":
        "SQLite database layout\n\n" +
        file +
        " is an empty SQLite placeholder; new-db-table initializes it on first use.\nNo tables or records are generated by this scaffold.\ntables/ is reserved for future table source files; new-db-table does not write migrations.\nUse new-db-table with path set to this folder, file set to " +
        file +
        ", and name set to the table name.\n",
    };
    for (const [relative, text] of Object.entries(artifacts))
      await writeFile(path.join(folder, relative), text, { flag: "wx" });
    return { path: folder, file, files: Object.keys(artifacts), tables: [] };
  } catch (error) {
    await rm(folder, { recursive: true, force: true });
    throw error;
  }
}

export async function executeTool(settings = {}) {
  try {
    const result = await create(settings);
    const paths = result.files
      ? result.files.map((file) => ({ path: result.path, file, type: "file" }))
      : [
          {
            path: result.path,
            file: result.file,
            name: result.name,
            type: "table",
          },
        ];
    return { return_type: "scaffold",
      status: "complete",
      settings,
      response: {
        path: result.path,
        file: result.file,
        paths,
        body: JSON.stringify(result),
        summary: { count: paths.length },
      },
    };
  } catch (error) {
    return { return_type: "scaffold",
      status: "error",
      settings,
      error: error instanceof Error ? error.message : String(error),
    };
  }
}

export const run = async (settings = {}) => {
  let result;
  try {
    result = { ...await executeTool(settings), return_type: "scaffold" };
  } catch (error) {
    result = { return_type: "scaffold", status: "error", settings, error: error instanceof Error ? error.message : String(error) };
  }
  try {
    const { finishToolUsage } = await import("../../../api/tool-usage/finish-tool-usage.ts");
    return await finishToolUsage(1791766641354, settings, result);
  } catch (error) {
    return { ...result, error: [result.error, `Usage reporting failed: ${error instanceof Error ? error.message : String(error)}`].filter(Boolean).join("\n") };
  }
};
